pub fn is_bot(user_agent: Option<&str>) -> bool {
    let ua = match user_agent {
        Some(ua) if !ua.trim().is_empty() => ua.to_ascii_lowercase(),
        _ => return true,
    };

    BOT_PATTERNS.iter().any(|&pattern| ua.contains(pattern))
}
